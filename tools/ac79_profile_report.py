"""Emit a conservative static RAM + runtime-profiler capability report."""
import argparse
import re
from pathlib import Path

def symbol(text, name):
    m = re.search(r"^([0-9a-fA-F]+) .*\\s" + re.escape(name) + r"$", text, re.M)
    return int(m.group(1), 16) if m else None

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--symbols", required=True, type=Path)
    p.add_argument("--output", required=True, type=Path)
    a = p.parse_args()
    syms = a.symbols.read_text(errors="replace")
    bss_end = symbol(syms, "_bss_end")
    pool_start = symbol(syms, "_pool_start")
    pool_end = symbol(syms, "_pool_end")
    ram_origin = 0x01C08000
    ram_size = 96 * 1024
    pool_size = 0x54000
    ram_used = bss_end - ram_origin if bss_end is not None else None
    pool_used = pool_end - pool_start if pool_start is not None and pool_end is not None else None
    lines = [
        "# SMK-37 HYBRID - AC79 memory and profiler report", "",
        "Generated by GitHub Actions from the final linked ELF symbol table.", "",
        "## Static memory (linker-derived)", "",
        "| Region | Used | Capacity | Remaining |", "|---|---:|---:|---:|",
    ]
    if ram_used is not None:
        lines.append(f"| .data + .bss | {ram_used} B | {ram_size} B | {ram_size-ram_used} B |")
    else:
        lines.append("| .data + .bss | unavailable | 98304 B | unavailable |")
    if pool_used is not None:
        lines.append(f"| .pool | {pool_used} B | {pool_size} B | {pool_size-pool_used} B |")
    else:
        lines.append(f"| .pool | unavailable | {pool_size} B | unavailable |")
    lines += [
        "", "## Runtime instrumentation linked into firmware", "",
        "| Metric | Instrumentation |", "|---|---|",
        "| AMB-1 / DUB-1 / ZEN-1 | TIMER4 calls, frames, total/last/max ticks |",
        "| GHOULBOX | TIMER4 around native mix_block() |",
        "| HYBRID mixer | TIMER4 aggregate duration |",
        "| DMA underruns | increments when DMA advances before render completes |",
        "| Stack watermark | sampled local stack-marker high-water against linker stack windows |",
        "| Audio scratch buffers | current block occupancy / registered capacity |",
        "", "## Hardware measurements", "",
        "**Pending physical SMK-37 run.** GitHub-hosted CI cannot measure live DSP CPU,",
        "stack high-water or underruns. The firmware snapshot API exposes these counters",
        "for debugger/CDC diagnostics; this report does not invent runtime values.", "",
        "Stack watermark is sampled rather than a guard-band proof. Buffer occupancy",
        "covers HYBRID audio scratch buffers only; it excludes private allocations in",
        "upstream engines and the Felucca pool."
    ]
    a.output.write_text("\n".join(lines) + "\n")
    print(a.output.read_text())

if __name__ == "__main__":
    main()
